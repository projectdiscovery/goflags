func TestConfigFileCascadeReplacesBuiltInCollections(t *testing.T) {
	tempDir := t.TempDir()
	systemConfig := filepath.Join(tempDir, "system.yaml")
	userConfig := filepath.Join(tempDir, "user.yaml")
	writeTestConfig(t, systemConfig, `
ports:
  - "81"
rate-limits:
  - system=2/s
severities:
  - low
dynamic:
  - system
`)
	writeTestConfig(t, userConfig, `
ports:
  - "82"
rate-limits:
  - user=3/s
severities:
  - medium
  - high
dynamic:
  - user
`)

	flagSet := NewFlagSet()
	var ports Port
	var rateLimits RateLimitMap
	var severities []string
	dynamic := []string{"compiled"}
	flagSet.PortVar(&ports, "ports", []string{"80"}, "test ports")
	flagSet.RateLimitMapVar(&rateLimits, "rate-limits", []string{"compiled=1/s"}, "test rate limits", StringSliceOptions)
	flagSet.EnumSliceVar(&severities, "severities", []EnumVariable{0}, "test severities", AllowdTypes{
		"low":    0,
		"medium": 1,
		"high":   2,
	})
	flagSet.DynamicVar(&dynamic, "dynamic", []string{"compiled"}, "test dynamic values")
	flagSet.SetConfigFilePaths(systemConfig, userConfig)

	require.NoError(t, flagSet.Parse(""))
	require.Equal(t, []int{82}, ports.AsPorts())
	require.Equal(t, map[string]RateLimit{
		"user": {MaxCount: 3, Duration: time.Second},
	}, rateLimits.AsMap())
	require.Equal(t, []string{"medium", "high"}, severities)
	require.Equal(t, []string{"user"}, dynamic)
}

func TestConfigFileCascadeReturnsValueError(t *testing.T) {
	tempDir := t.TempDir()
	lowerConfig := filepath.Join(tempDir, "lower.yaml")
	higherConfig := filepath.Join(tempDir, "higher.yaml")
	writeTestConfig(t, lowerConfig, "count: 2\n")
	writeTestConfig(t, higherConfig, "count: not-an-integer\n")

	flagSet := NewFlagSet()
	var count int
	flagSet.IntVar(&count, "count", 1, "test count")
	flagSet.SetConfigFilePaths(lowerConfig, higherConfig)

	err := flagSet.Parse("")
	require.ErrorContains(t, err, `set config option "count"`)
	require.ErrorContains(t, err, fmt.Sprintf("%q", higherConfig))
	require.NotContains(t, err.Error(), fmt.Sprintf("%q", lowerConfig))
}

func BenchmarkMergeConfigAssignments(b *testing.B) {
	for _, size := range []int{100, 500, 1000} {
		flagSet := NewFlagSet()
		values := make([]string, size)
		targets := make([]configTarget, size)
		for i := range size {
			name := fmt.Sprintf("flag-%d", i)
			flagSet.CommandLine.StringVar(&values[i], name, "", "benchmark flag")
			targets[i] = newConfigTarget(nil, name, flagSet.CommandLine.Lookup(name).Value)
		}

		b.Run(fmt.Sprintf("flags=%d", size), func(b *testing.B) {
			for b.Loop() {
				assignments := newConfigAssignments(size)
				for _, target := range targets {
					assignments.merge(configAssignment{target: target})
				}
				if len(assignments.ordered) != size {
					b.Fatalf("got %d assignments, want %d", len(assignments.ordered), size)
				}
			}
		})
	}
}


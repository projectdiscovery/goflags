func TestConfigFileCascade(t *testing.T) {
	tempDir := t.TempDir()
	systemConfig := filepath.Join(tempDir, "system.yaml")
	userConfig := filepath.Join(tempDir, "user.yaml")
	writeTestConfig(t, systemConfig, `
value: system
system-only: true
items:
  - system
values:
  - system=1
config-only:
  - system
aliased: system
`)
	writeTestConfig(t, userConfig, `
value: user
items:
  - user
values:
  - user=2
config-only:
  - user
a: user
`)

	flagSet := NewFlagSet()
	var (
		value      string
		systemOnly bool
		items      StringSlice
		values     RuntimeMap
		configOnly StringSlice
		aliased    string
	)
	flagSet.StringVar(&value, "value", "compiled", "test value")
	flagSet.BoolVar(&systemOnly, "system-only", false, "system value")
	flagSet.StringSliceVar(&items, "items", []string{"compiled"}, "test items", StringSliceOptions)
	flagSet.RuntimeMapVar(&values, "values", []string{"compiled=1"}, "test values")
	flagSet.StringSliceVarConfigOnly(&configOnly, "config-only", []string{"compiled"}, "config-only value")
	flagSet.StringVarP(&aliased, "aliased", "a", "compiled", "aliased value")
	flagSet.SetConfigFilePaths(systemConfig, userConfig)

	require.NoError(t, flagSet.Parse(""))
	require.Equal(t, "user", value)
	require.True(t, systemOnly)
	require.Equal(t, StringSlice{"user"}, items)
	require.Equal(t, map[string]interface{}{"user": "2"}, values.AsMap())
	require.Equal(t, StringSlice{"user"}, configOnly)
	require.Equal(t, "user", aliased)
}

